/**
 * Table 506.3.3 frontage increase factor.
 * Width bands: 20–<25, 25–<30, ≥30. Perimeter bands: 25–<50, 50–<75, 75–100.
 */
export function frontageFactor(percent: number | null, widthFt: number | null): number {
  if (percent == null || widthFt == null) return 0;
  if (percent < 25 || widthFt < 20) return 0;
  const perimeterBand = percent < 50 ? 0 : percent < 75 ? 1 : 2;
  const widthBand = widthFt < 25 ? 0 : widthFt < 30 ? 1 : 2;
  const table = [
    [0.17, 0.21, 0.25],
    [0.33, 0.42, 0.5],
    [0.5, 0.63, 0.75],
  ];
  return table[perimeterBand][widthBand];
}

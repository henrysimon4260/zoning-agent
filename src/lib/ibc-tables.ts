export type Cell = number | "UL" | null;

function parseRow(spec: string): Cell[] {
  const cells = spec.split(",").map((part) => {
    if (part === "UL") return "UL" as const;
    if (part === "-" || part === "") return null;
    return Number(part);
  });
  if (cells.length !== 12 || cells.some((cell) => typeof cell === "number" && Number.isNaN(cell))) {
    throw new Error(`Bad IBC row: ${spec}`);
  }
  return cells;
}

export function cellAt(row: Cell[], type: ConstructionType): Cell {
  return row[CONSTRUCTION_TYPES.indexOf(type)] ?? null;
}


type StoryBlock = {
  NS: Cell[];
  S: Cell[];
  S13R?: Cell[];
  S13D?: Cell[];
};

type AreaBlock = {
  NS: Cell[];
  S1: Cell[];
  SM: Cell[];
  S13R?: Cell[];
};

function stories(ns: string, s: string, extra?: Partial<Pick<StoryBlock, "S13R" | "S13D">>): StoryBlock {
  return { NS: parseRow(ns), S: parseRow(s), ...extra };
}

function area(ns: string, s1: string, sm: string, s13r?: string): AreaBlock {
  return {
    NS: parseRow(ns),
    S1: parseRow(s1),
    SM: parseRow(sm),
    ...(s13r ? { S13R: parseRow(s13r) } : {}),
  };
}

